/// @brief 滞回比较器核心处理（必须周期性调用）
/// @param hcomp 滞回比较器结构体指针
/// @author doubao
void Hysteresis_Comp_Process_Add_f32(Hysteresis_Comp_TypeDef_f32_t *hcomp, float analog_input)
{
     // 1. 复位优先
     if (hcomp->reset)
     {
          hcomp->comp_out = 0;
          hcomp->delay_cnt = 0;
          return;
     }

     // 2. 未使能
     if (!hcomp->enable)
     {
          hcomp->comp_out = 0;
          hcomp->delay_cnt = 0;
          return;
     }

     // 3. 滞回核心逻辑
     switch (hcomp->comp_out)
     {
     case 0:
          /* code */
          if (analog_input <= hcomp->threshold_high)
          {

               hcomp->delay_cnt = 0;
          }
          else
          {
               hcomp->delay_cnt++;
               if(hcomp->delay_cnt >= hcomp->delay_time)
               {
                    hcomp->comp_out = 1;
               }
          }
          break;
     case 1:
          if (analog_input >= hcomp->threshold_low)
          {
               hcomp->delay_cnt = 0;
          }
          else
          {
               hcomp->delay_cnt++;
               if(hcomp->delay_cnt >= hcomp->delay_time)
               {
                    hcomp->comp_out = 0;
               }
          }
          break;
     default:
          hcomp->comp_out = 0;
          break;
     }
}



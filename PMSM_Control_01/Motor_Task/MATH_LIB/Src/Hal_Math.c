/// @brief 斜波函数，cur_value向end_value以Sub_Step和Add_Step的速度靠近
/// @param end_value 目标值
/// @param cur_value 当前值
/// @param Sub_Step 减速步长
/// @param Add_Step 加速步长
/// @return 更新后的值
q31_t Oblique_Wave_q31(q31_t end_value, q31_t cur_value, q31_t Add_Step, q31_t Sub_Step)
{
     float cur = cur_value;
     if (cur_value < end_value)
     {
          cur += Add_Step;
          if (cur > end_value)
          {
               cur = end_value;
          }
     }
     else if (cur_value > end_value)
     {
          cur -= Sub_Step;
          if (cur < end_value)
          {
               cur = end_value;
          }
     }
     return cur;
}

